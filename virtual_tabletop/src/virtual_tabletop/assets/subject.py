"""The monkey: a right arm model and its mirror image as the left arm.

The arm file is ``arm_file`` in ``config/subject.yaml``
(``monkey_arm/right_arm_fingers_v0.xml``: 7 arm joints plus 16 finger
joints, no muscles). It is a right arm whose own frame has +x
forward, +z up and +y toward the body midline. The left arm is generated by
reflecting it across that frame's y = 0 plane (M = diag(1, -1, 1)), applied
consistently to every element:

- positions (bodies, joints, sites, inertials): ``(x, y, z) -> (x, -y, z)``;
- orientations ``R -> M R M``: quaternion ``(w, x, y, z) -> (w, -x, y, -z)``;
- hinge axes (pseudo-vectors) ``a -> -M a``: ``(x, y, z) -> (-x, y, -z)``.
  With this, joint ranges are unchanged and the same angle gives the
  mirrored posture;
- inertia tensors ``I -> M I M`` (Ixy and Iyz change sign);
- meshes: vertices mirrored and triangle winding reversed (cached STLs).

Arm files must be self-contained (no ``<include>``).

Names in a built model are prefixed ``monkey/<side>/`` (:func:`prefix`);
helpers below look up each arm's joints, bodies and reaching site.
"""

import xml.etree.ElementTree as ET
from pathlib import Path

import trimesh

from virtual_tabletop import paths

SIDES = ("right", "left")


def _floats(text: str) -> list[float]:
    return [float(v) for v in text.split()]


def _fmt(values) -> str:
    return " ".join(repr(float(v)) for v in values)


def _mirror_pos(text: str) -> str:
    x, y, z = _floats(text)
    return _fmt((x, -y, z))


def _mirror_quat(text: str) -> str:
    w, x, y, z = _floats(text)
    return _fmt((w, -x, y, -z))


def _mirror_axis(text: str) -> str:
    x, y, z = _floats(text)
    return _fmt((-x, y, -z))


def _mirror_fullinertia(text: str) -> str:
    ixx, iyy, izz, ixy, ixz, iyz = _floats(text)
    return _fmt((ixx, iyy, izz, -ixy, ixz, -iyz))


def _mirror_mesh(source: Path, out_dir: Path) -> Path:
    out = out_dir / f"{source.stem}_mirrored.stl"
    if not out.exists() or out.stat().st_mtime < source.stat().st_mtime:
        mesh = trimesh.load_mesh(source)
        mesh.vertices[:, 1] *= -1
        mesh.invert()  # restore outward normals after the reflection
        out_dir.mkdir(parents=True, exist_ok=True)
        mesh.export(out)
    return out


def mirrored_arm_file(right_arm: Path, output: Path | None = None) -> Path:
    """Write the left-arm MJCF mirrored from ``right_arm``.

    Returns:
        The left-arm file (mesh paths absolute), in the generated cache.
    """
    output = output or paths.GENERATED_DIR / "monkey_left_arm.xml"
    tree = ET.parse(right_arm)
    root = tree.getroot()
    root.set("model", (root.get("model") or "arm") + " (mirrored left)")
    mesh_dir = paths.CACHE_DIR / "meshes" / "monkey_left"
    for mesh in root.iter("mesh"):
        if mesh.get("file"):
            source = (right_arm.parent / mesh.get("file")).resolve()
            mesh.set("file", str(_mirror_mesh(source, mesh_dir)))
    for element in root.iter():
        tag = element.tag
        if "pos" in element.attrib and tag in (
            "body",
            "joint",
            "site",
            "inertial",
            "geom",
        ):
            element.set("pos", _mirror_pos(element.get("pos")))
        if "quat" in element.attrib:
            element.set("quat", _mirror_quat(element.get("quat")))
        if tag == "joint" and "axis" in element.attrib:
            element.set("axis", _mirror_axis(element.get("axis")))
        if tag == "inertial" and "fullinertia" in element.attrib:
            element.set(
                "fullinertia", _mirror_fullinertia(element.get("fullinertia"))
            )
        for unsupported in (
            "euler",
            "axisangle",
            "xyaxes",
            "zaxis",
            "fromto",
            "iquat",
        ):
            if unsupported in element.attrib:
                raise NotImplementedError(
                    f"Mirroring <{tag} {unsupported}=...> is not implemented"
                )
    output.parent.mkdir(parents=True, exist_ok=True)
    tree.write(output)
    return output


def arm_file(side: str, right_arm: Path) -> Path:
    """The arm model file for ``side`` (the left one is generated)."""
    if side == "right":
        return right_arm
    if side == "left":
        return mirrored_arm_file(right_arm)
    raise ValueError(side)


# --- names in a built model (prefix ``monkey/<side>/``) ---------------------

#: Prefix of every element of the monkey in a built model.
SUBJECT_PREFIX = "monkey/"

#: Each hand's reaching point: a site at the middle fingertip.
HAND_SITE_NAME = "fingertip"

#: Name prefixes of finger joints.
FINGERS = ("thumb_", "index_", "middle_", "ring_", "pinky_")


def prefix(side: str) -> str:
    """Name prefix of one monkey arm, e.g. ``monkey/right/``."""
    return f"{SUBJECT_PREFIX}{side}/"


def hand_site(side: str) -> str:
    """Name of ``side``'s reaching-point site."""
    return prefix(side) + HAND_SITE_NAME


def is_finger_joint(name: str) -> bool:
    """Whether a (possibly prefixed) joint name is a finger joint."""
    return name.rsplit("/", 1)[-1].startswith(FINGERS)


def sides_in(model) -> list[str]:
    """Monkey arms present in ``model`` (in ``SIDES`` order)."""
    names = {model.joint(j).name for j in range(model.njnt)}
    return [s for s in SIDES if any(n.startswith(prefix(s)) for n in names)]


def joint_names(model, side: str) -> list[str]:
    return [
        model.joint(j).name
        for j in range(model.njnt)
        if model.joint(j).name.startswith(prefix(side))
    ]


def arm_joint_names(model, side: str) -> list[str]:
    """``side``'s joints without the fingers (the 7 arm joints)."""
    return [n for n in joint_names(model, side) if not is_finger_joint(n)]


def body_ids(model, side: str) -> set[int]:
    return {
        b
        for b in range(model.nbody)
        if model.body(b).name.startswith(prefix(side))
    }


def shoulder_position(model, data, side: str):
    return data.xpos[model.body(prefix(side) + "humerus").id]
